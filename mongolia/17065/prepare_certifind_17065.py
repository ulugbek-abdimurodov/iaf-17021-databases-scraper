def pc02_groups(pdf: Path) -> list[tuple[str, str, str]]:
    """PC 02 has a text layer: column 1 group, last column normative document."""
    rows, _ = cf.pdf_rows(pdf)
    groups: "OrderedDict[str, list[str]]" = OrderedDict()
    cur = None
    for r in rows:
        c = [cf.clean(x) for x in r]
        if len(c) < 3:
            continue
        if c[0] and not re.fullmatch(r"[\d ]+", c[0]) and "Бүтээгдэхүүний" not in c[0] and "ангилал" not in c[0]:
            cur = c[0]
        if cur and c[-1] and not re.fullmatch(r"[\d ]+", c[-1]):
            groups.setdefault(cur, []).append(c[-1])
    ind = {"Мэрэгчидтэй": "chemicals", "Ойн хөнөөлт": "chemicals", "Тэжээлийн": "agriculture"}
    out = []
    for g, docs in groups.items():
        industry = next((v for k, v in ind.items() if g.startswith(k)), "health")
        out.append((g, "; ".join(dict.fromkeys(docs)), industry))
    return out


def phone(raw: str) -> str:
    d = re.sub(r"\D", "", (raw or "").split()[0] if raw else "")
    return f"+976 {d[:4]} {d[4:]}" if len(d) == 8 else ""


def main():
    scrape, today = cf.cli(HERE)
    raw = json.load(open(scrape / "mnas_17065_raw.json", encoding="utf-8"))
    notes, bodies = [], []
    for r in raw:
        reg = r["registration_no"]
        b = cf.Body(reg=reg, name=NAMES.get(reg, r["org_name"]), country="Mongolia", phone=phone(r["phone"]),
                    email=re.split(r"\s+", (r["email"] or "").strip())[0], website=r.get("website") or "",
                    address=r.get("address") or "", issued=r["issued"], expiry=r["expiry"],
                    proof_url=(r["annex_urls"] or [URL])[0], source_url=URL,
                    active=r["status"] == VALID, status_note=r["status"])
        groups = pc02_groups(scrape / "pdfs" / "PC_02_1.pdf") if reg == "PC 02" else GROUPS.get(reg, [])
        for prod, norm, ind in groups:
            sch = cf.scheme_of(f"{prod} {norm}")
