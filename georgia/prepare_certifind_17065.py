"""GAC (Georgia) ISO/IEC 17065 -> CertiFind dataset data/gac-georgia-17065.

Usage: python prepare_certifind_17065.py [<dataset dir>] [--today YYYY-MM-DD]

Input: gac_17065_raw.json (register API, ACTIVE bodies with a 17065 evaluation standard). Scope comes from the
API's numbered scope.en / scope.ge lists (no PDF parsing). AB code is GAC-GE: "GAC" is already the GCC
Accreditation Center (Saudi Arabia). No scheme codes: the scopes are product groups under Georgian technical
regulations (national), so lines are text + industry only.
"""
import csv, json, os, re, sys
from collections import Counter
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
args = [a for i, a in enumerate(sys.argv[1:], 1) if not a.startswith("--") and sys.argv[i - 1] != "--today"]
OUT = args[0] if args else os.path.join(HERE, "..", "..", "certifind", "data", "gac-georgia-17065")
TODAY = sys.argv[sys.argv.index("--today") + 1] if "--today" in sys.argv else date.today().isoformat()
AB = "GAC-GE"

INDUSTRY_WORDS = [(re.compile(p, re.I), ind) for p, ind in [
    (r"tobacco|cigarette", "other_manufacturing"),
    (r"power plant|electricity", "energy"),
    (r"steel|ferrous|joist", "metals"),
    (r"cement|concrete|asphalt|sand|gravel|construction", "construction"),
    (r"water|beverage|beer|tea|honey|laurel|adjika|fruit|vegetable|egg|flour|confectioner|cake|grain", "food"),
]]
PS_COLS = ["certificate_number", "line_no", "scheme", "industry", "product_text", "product_text_en",
           "scheme_text", "normative_docs", "standard_refs", "status"]


def items(text):
    """Split '1. a; 2. b 3.c' into ['a', 'b', 'c'] (numbered items)."""
    parts = re.split(r"(?:^|[;.\s])\s*\d{1,2}\s*\.(?!\d)", " " + (text or ""))
    return [p.strip(" ;.") for p in parts if p.strip(" ;.")]


def phone(p):
    d = re.sub(r"[^\d+]", "", p or "")
    if not d.startswith("+995") or len(d) != 13:
        return ""
    d = d[4:]
    return f"+995 {d[:2]} {d[2:5]} {d[5:7]} {d[7:]}"


def industry(t):
    return next((ind for rx, ind in INDUSTRY_WORDS if rx.search(t)), "")


recs = json.load(open(os.path.join(HERE, "gac_17065_raw.json"), encoding="utf-8"))
bodies, accs, ps, notes = [], [], [], []
for r in recs:
    reg = r["registration_no"]
    ph = phone(r["phone"])
    if r["phone"] and not ph:
        notes.append(f"- {reg}: phone `{r['phone']}` not normalisable, left empty")
    bodies.append({"name": r["name"].strip(), "country": "Georgia", "registration_no": reg, "phone": ph,
                   "email": r["email"].strip().lower(), "website": r["website"], "address": r["address"].strip(),
                   "source_url": f"https://gac.gov.ge/en/accredited-bodies/{r['id']}", "verified_at": ""})
    accs.append({"ab_code": AB, "certificate_number": reg, "body_name": r["name"].strip(),
                 "accreditation_standard": "ISO/IEC 17065", "status": "ACTIVE", "issue_date": r["issued"],
                 "expiry_date": r["expiry"], "proof_url": f"https://gac.gov.ge/en/accredited-bodies/{r['id']}"})
    en, ge = items(r["scope_en"]), items(r["scope_ge"])
    paired = len(en) == len(ge)
    if not paired:
        notes.append(f"- {reg}: English scope has {len(en)} items, Georgian {len(ge)}; imported English only "
                     f"(the register changelog shows the Georgian text still lists withdrawn items)")
    for i, t in enumerate(en, 1):
        ind = industry(t)
        assert ind, (reg, t)
        ps.append({"certificate_number": reg, "line_no": i, "scheme": "", "industry": ind,
                   "product_text": ge[i - 1] if paired else t, "product_text_en": t if paired else "",
                   "scheme_text": "", "normative_docs": "", "standard_refs": "", "status": "ACTIVE"})

os.makedirs(OUT, exist_ok=True)
def write(name, cols, rows):
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, cols, lineterminator="\n"); w.writeheader(); w.writerows(rows)
write("bodies.csv", list(bodies[0]), bodies)
write("accreditations.csv", list(accs[0]), accs)
write("scopes.csv", ["certificate_number", "certification_standard", "ea_codes", "status", "scope_note"], [])
write("product_scopes.csv", PS_COLS, ps)

ind = Counter(p["industry"] for p in ps)
with open(os.path.join(HERE, "gac_17065_review.md"), "w", encoding="utf-8") as f:
    f.write("# GAC (Georgia) ISO/IEC 17065 - review\n\nGenerated by `prepare_certifind_17065.py`.\n\n"
            "- AB code `GAC-GE` (added in a migration): `GAC` is already the GCC Accreditation Center.\n"
            "- Scope from the register API (scope.en / scope.ge numbered lists); no standards or schemes are named, "
            "so no `scheme` and no `standard_refs`. Georgian technical regulations are national: text + industry.\n"
            "- Expiry dates are not published by the API (empty).\n- No body found in other datasets.\n"
            + "\n".join(notes) + "\n\n## Lines by industry\n\n" + "\n".join(f"- {k}: {v}" for k, v in ind.most_common()) + "\n")
print(f"Bodies: {len(bodies)}\nAccreditations: {len(accs)}\nProduct lines: {len(ps)} (0 with scheme)\n" + "\n".join(notes))
